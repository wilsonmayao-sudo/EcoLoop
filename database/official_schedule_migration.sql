-- EcoLoop: Official Garbage Collection Schedule & Geographic Data Migration
-- Source: Garbage-Collection-Scheme-Clustering-Updated-2026-Final.pdf (SWMO Naga City)
-- Reversible, idempotent migration (safe to run multiple times)
-- =============================================================================

BEGIN;

-- 1. Extend public.bins with schedule & verification metadata (non-breaking)
ALTER TABLE public.bins
  ADD COLUMN IF NOT EXISTS area_code text,
  ADD COLUMN IF NOT EXISTS schedule_days text[] DEFAULT '{}'::text[],
  ADD COLUMN IF NOT EXISTS schedule_time_window text,
  ADD COLUMN IF NOT EXISTS waste_category text,
  ADD COLUMN IF NOT EXISTS coordinate_status text NOT NULL DEFAULT 'verified';

ALTER TABLE public.bins
  ALTER COLUMN collection_status SET DEFAULT 'pending';

UPDATE public.bins
SET collection_status = 'pending'
WHERE collection_status = '''pending''::text' OR collection_status IS NULL;

-- 2. Extend public.routes with official SWMO Area schedule metadata (non-breaking)
ALTER TABLE public.routes
  ADD COLUMN IF NOT EXISTS area_code text,
  ADD COLUMN IF NOT EXISTS scheduled_days text[] DEFAULT '{}'::text[],
  ADD COLUMN IF NOT EXISTS shift_label text,
  ADD COLUMN IF NOT EXISTS waste_category text;

-- 3. Create public.collection_schedules table
CREATE TABLE IF NOT EXISTS public.collection_schedules (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_code            text NOT NULL,
  area_name            text NOT NULL,
  shift_label          text,
  stop_order           integer NOT NULL,
  location_name        text NOT NULL,
  stop_type            text NOT NULL DEFAULT 'collection',
  barangay             text,
  days_of_week         text[] NOT NULL DEFAULT '{}'::text[],
  day_times            jsonb NOT NULL DEFAULT '{}'::jsonb,
  scheduled_time       text,
  waste_category       text,
  assigned_truck_note  text,
  special_instructions text,
  bin_id               bigint REFERENCES public.bins(id) ON DELETE SET NULL,
  latitude             double precision,
  longitude            double precision,
  coordinate_status    text NOT NULL DEFAULT 'needs_verification',
  monitor_name         text,
  source_reference     text NOT NULL DEFAULT 'Garbage-Collection-Scheme-Clustering-Updated-2026-Final.pdf',
  source_page          integer,
  is_active            boolean NOT NULL DEFAULT true,
  created_at           timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at           timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT collection_schedules_area_stop_unique UNIQUE (area_code, stop_order),
  CONSTRAINT collection_schedules_stop_order_check CHECK (stop_order > 0)
);

CREATE INDEX IF NOT EXISTS idx_collection_schedules_area ON public.collection_schedules (area_code, stop_order);
CREATE INDEX IF NOT EXISTS idx_collection_schedules_barangay ON public.collection_schedules (barangay);
CREATE INDEX IF NOT EXISTS idx_collection_schedules_bin_id ON public.collection_schedules (bin_id);
CREATE INDEX IF NOT EXISTS idx_collection_schedules_days ON public.collection_schedules USING gin (days_of_week);

-- Updated_at trigger
DROP TRIGGER IF EXISTS trg_collection_schedules_updated_at ON public.collection_schedules;
CREATE TRIGGER trg_collection_schedules_updated_at
  BEFORE UPDATE ON public.collection_schedules
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

-- Enable RLS
ALTER TABLE public.collection_schedules ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "collection_schedules_read_authenticated" ON public.collection_schedules;
CREATE POLICY "collection_schedules_read_authenticated" ON public.collection_schedules
  FOR SELECT
  TO PUBLIC
  USING (
    public.is_admin(auth.uid())
    OR public.is_dispatcher(auth.uid())
    OR public.is_supervisor(auth.uid())
    OR public.is_driver(auth.uid())
    OR (
      public.current_profile_is_active()
      AND public.current_app_role() = ANY (ARRAY['admin'::text, 'dispatcher'::text, 'supervisor'::text, 'truck_driver'::text])
    )
  );

DROP POLICY IF EXISTS "collection_schedules_manage_admin_dispatcher" ON public.collection_schedules;
CREATE POLICY "collection_schedules_manage_admin_dispatcher" ON public.collection_schedules
  FOR ALL
  TO PUBLIC
  USING (
    public.is_admin(auth.uid())
    OR public.is_dispatcher(auth.uid())
    OR (
      public.current_profile_is_active()
      AND public.current_app_role() = ANY (ARRAY['admin'::text, 'dispatcher'::text])
    )
  )
  WITH CHECK (
    public.is_admin(auth.uid())
    OR public.is_dispatcher(auth.uid())
    OR (
      public.current_profile_is_active()
      AND public.current_app_role() = ANY (ARRAY['admin'::text, 'dispatcher'::text])
    )
  );

REVOKE ALL ON TABLE public.collection_schedules FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.collection_schedules TO authenticated, service_role, postgres;

COMMIT;
