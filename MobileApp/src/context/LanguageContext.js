const LanguageContext = createContext();

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState('en'); // 'en' for English, 'tl' for Tagalog

  useEffect(() => {
    loadLanguagePreference();
  }, []);

  const loadLanguagePreference = async () => {
    try {
      const savedLanguage = await AsyncStorage.getItem('language');
      if (savedLanguage !== null) {
        setLanguage(savedLanguage);
      }
    } catch (error) {
      // Silent error handling - will use default (English)
    }
  };

  const changeLanguage = async (lang) => {
    try {
      setLanguage(lang);
      await AsyncStorage.setItem('language', lang);
    } catch (error) {
      // Silent error handling - language change may not persist
    }
  };

  const t = useCallback(
    (key, fallback, vars) => {
      const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
      let text = dict[key] ?? TRANSLATIONS.en[key] ?? (typeof fallback === 'string' ? fallback : key);
      const replacements = typeof fallback === 'object' && fallback !== null ? fallback : vars;
      if (replacements && typeof text === 'string') {
        Object.entries(replacements).forEach(([k, v]) => {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v ?? ''));
        });
      }
      return text;
    },
    [language],
  );

  const value = {
    language,
    changeLanguage,
    isEnglish: language === 'en',
    isTagalog: language === 'tl',
    t,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

